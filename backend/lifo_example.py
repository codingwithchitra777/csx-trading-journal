print("LIFO TRADING JOURNAL - EXAMPLE OUTPUTS")
print("=" * 60)

print("\n📍 EXAMPLE 1: Selling with LIFO Matching")
print("-" * 60)
print("Previous trades:")
print("  ✅ BUY confirmed | Seq #1")
print("     ABC: 100 @ 7,000 riel")
print()
print("  ✅ BUY confirmed | Seq #2")
print("     ABC: 100 @ 7,100 riel")
print()
print("  ✅ BUY confirmed | Seq #3")
print("     ABC: 100 @ 7,200 riel (most recent)")
print()
print("Now selling 150 shares:")
print("  ✅ SELL confirmed | Seq #4 | P/L: +50,000 riel")
print("  📦 Matched: #3 (100@7,200), #2 (50@7,100)")
