print("\n📍 EXAMPLE 2: Stock Details Command")
print("-" * 60)
print("Command: /stock ABC")
print()
print("📋 **ABC - Stock Details (LIFO)**")
print()
print("**📥 BUY Orders (Most Recent First):**")
print("🟢 #3: 100@7,200 | Remaining: 0")
print("🟢 #2: 100@7,100 | Remaining: 50")
