print("Total Sold: 150")
print("Remaining: 150")
print("Realised P/L: +50,000 riel")

print("\n" + "=" * 60)
print("KEY DIFFERENCES: FIFO vs LIFO")
print("=" * 60)
print()
print("FIFO (First In First Out):")
print("  ❌ Would match with OLDEST purchases first")
print("  ❌ In example: Would match #1 (7,000) and #2 (7,100)")
print("  ❌ Lower profit: 100×(7,500-7,000) + 50×(7,500-7,100)")
print("  ❌             = 50,000 + 20,000 = 70,000 riel")
print()
print("LIFO (Last In First Out):")
print("  ✅ Matches with NEWEST purchases first")
print("  ✅ In example: Matches #3 (7,200) and #2 (7,100)")
print("  ✅ Actual profit: 100×(7,500-7,200) + 50×(7,500-7,100)")
print("  ✅              = 30,000 + 20,000 = 50,000 riel")
print()
print("=" * 60)
print("✅ Your bot now uses LIFO matching!")
